import {packager} from '@electron/packager';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd();
const stage=path.join(root,'.desktop-stage');
await fs.rm(stage,{recursive:true,force:true});await fs.mkdir(stage,{recursive:true});
await fs.cp(path.join(root,'dist'),path.join(stage,'dist'),{recursive:true});
await fs.cp(path.join(root,'desktop'),path.join(stage,'desktop'),{recursive:true});
const pkg=JSON.parse(await fs.readFile('package.json','utf8'));await fs.writeFile(path.join(stage,'package.json'),JSON.stringify({name:'easy-text',productName:'easy text',version:pkg.version,description:'ET local code editor',type:'module',main:'desktop/main.mjs'}));
const electron=JSON.parse(await fs.readFile('node_modules/electron/package.json','utf8')).version;
const output=await packager({dir:stage,out:path.join(root,'dist-desktop'),name:'easy text',executableName:'easy text',appBundleId:'local.easytext.editor',icon:path.join(root,'desktop/assets/easy-text.icns'),appVersion:pkg.version,electronVersion:electron,platform:'darwin',arch:'arm64',overwrite:true,asar:true,prune:false,osxSign:false});
console.log(output.join('\n'));await fs.rm(stage,{recursive:true,force:true});
